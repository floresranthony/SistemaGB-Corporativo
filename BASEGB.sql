create or replace function public.tareo_usuario_actual_id() returns int language sql stable security definer set search_path=public as $$ select id from public.usuarios where activo and (auth_user_id=auth.uid() or lower(correo)=lower(coalesce(auth.jwt()->>'email',''))) limit 1 $$;
create or replace function public.tareo_rol_actual() returns text language sql stable security definer set search_path=public as $$ select r.codigo from public.usuarios u join public.roles r on r.id=u.rol_id where u.id=public.tareo_usuario_actual_id() $$;
create or replace function public.tareo_es_admin() returns boolean language sql stable security definer set search_path=public as $$ select coalesce(public.tareo_rol_actual() in ('admin','gerencia'),false) $$;
create or replace function public.tareo_puede_operar_sede(p_sede_id int) returns boolean language sql stable security definer set search_path=public as $$ select public.tareo_es_admin() or exists(select 1 from public.usuario_sedes where usuario_id=public.tareo_usuario_actual_id() and sede_id=p_sede_id) $$;

create or replace function public.tareo_validar_marcacion() returns trigger language plpgsql security definer set search_path=public as $$
declare p public.tareo_periodos; v public.vinculos_laborales; clase text; total_horas numeric; avisos jsonb:='[]'::jsonb;
begin
 select * into p from public.tareo_periodos where id=new.periodo_id; if p is null then raise exception 'Periodo no encontrado'; end if;
 if new.fecha < make_date(p.anio,p.mes,1) or new.fecha > (make_date(p.anio,p.mes,1)+interval '1 month - 1 day')::date then raise exception 'La fecha no pertenece al periodo'; end if;
 if p.estado not in ('Borrador','Observado','Corregido') then raise exception 'El periodo está bloqueado'; end if;
 if new.sede_trabajada_id<>p.sede_id or not public.tareo_puede_operar_sede(new.sede_trabajada_id) then raise exception 'No tiene acceso a la sede trabajada'; end if;
 select * into v from public.vinculos_laborales where id=new.vinculo_laboral_id; if v.fecha_cese is not null and new.fecha>v.fecha_cese then raise exception 'No se permiten horas posteriores al cese'; end if;
 select clase into clase from public.tipos_marcacion where id=new.tipo_marcacion_id and activo; if clase is null or ((clase='HORAS')<>(new.horas>0)) then raise exception 'Tipo u horas de marcación inválidos'; end if;
 if exists(select 1 from public.vacaciones_historico where vinculo_laboral_id=new.vinculo_laboral_id and new.fecha between fecha_inicio and fecha_fin) and new.horas>0 then avisos:=avisos||jsonb_build_array('Horas registradas durante vacaciones'); end if;
 select coalesce(sum(horas),0) into total_horas from public.tareo_marcaciones where vinculo_laboral_id=new.vinculo_laboral_id and fecha=new.fecha and id is distinct from new.id; if total_horas+new.horas>16 then avisos:=avisos||jsonb_build_array('Jornada diaria inusual'); end if;
 new.cliente_id:=(select cliente_id from public.sedes where id=new.sede_trabajada_id); new.supervisor_registro_id:=public.tareo_usuario_actual_id(); new.actualizado_por_id:=public.tareo_usuario_actual_id(); new.actualizado_en:=now(); new.alertas:=avisos;
 if tg_op='INSERT' then new.creado_por_id:=public.tareo_usuario_actual_id(); new.creado_en:=now(); end if; return new;
end $$;
drop trigger if exists trg_tareo_validar_marcacion on public.tareo_marcaciones;
create trigger trg_tareo_validar_marcacion before insert or update on public.tareo_marcaciones for each row execute function public.tareo_validar_marcacion();

