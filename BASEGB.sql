create or replace function public.tareo_cambiar_estado(p_periodo_id bigint,p_accion text,p_observacion text default null,p_motivo text default null) returns public.tareo_periodos language plpgsql security definer set search_path=public as $$
declare p public.tareo_periodos; u int:=public.tareo_usuario_actual_id(); rol text:=public.tareo_rol_actual(); siguiente text;
begin select * into p from public.tareo_periodos where id=p_periodo_id for update; if p is null then raise exception 'Periodo no encontrado'; end if;
 siguiente:=case p_accion when 'enviar' then case when p.estado='Borrador' then 'Enviado' when p.estado='Observado' then 'Corregido' when p.estado='Corregido' then 'Enviado' end when 'observar' then case when p.estado in ('Enviado','Corregido') and rol in ('planilla','admin') then 'Observado' end when 'aprobar' then case when p.estado in ('Enviado','Corregido') and rol in ('planilla','admin') then 'Aprobado' end when 'cerrar' then case when p.estado='Aprobado' and rol in ('planilla','admin') then 'Cerrado' end when 'reabrir' then case when p.estado in ('Aprobado','Cerrado') and rol='admin' then 'Borrador' end end;
 if siguiente is null then raise exception 'Transición no permitida'; end if; if p_accion='reabrir' and nullif(trim(coalesce(p_motivo,'')),'') is null then raise exception 'La reapertura requiere motivo'; end if;
 update public.tareo_periodos set estado=siguiente,observaciones=coalesce(p_observacion,observaciones),enviado_en=case when siguiente='Enviado' then now() else enviado_en end,enviado_por_id=case when siguiente='Enviado' then u else enviado_por_id end,aprobado_en=case when siguiente='Aprobado' then now() else aprobado_en end,aprobado_por_id=case when siguiente='Aprobado' then u else aprobado_por_id end,cerrado_en=case when siguiente='Cerrado' then now() else cerrado_en end,cerrado_por_id=case when siguiente='Cerrado' then u else cerrado_por_id end,actualizado_en=now() where id=p_periodo_id returning * into p;
 insert into public.tareo_auditoria(periodo_id,accion,usuario_id,motivo,estado_periodo) values(p.id,upper(p_accion),u,coalesce(p_motivo,p_observacion),p.estado); return p;
end $$;

create or replace view public.v_tareo_consolidado as
select tm.periodo_id,tp.anio,tp.mes,tm.vinculo_laboral_id,vl.persona_id,tm.sede_trabajada_id,tm.cliente_id,sum(tm.horas) total_horas,count(distinct tm.fecha) filter(where tm.horas>0) dias_laborados,count(*) filter(where t.codigo='D') descansos,count(*) filter(where t.codigo='DFE') descansos_feriado,count(*) filter(where t.codigo='FI') faltas_injustificadas,count(*) filter(where t.codigo='FJ') faltas_justificadas,count(*) filter(where t.codigo in ('P','PSG','PCG','PG')) permisos,count(*) filter(where t.codigo='DM') descansos_medicos,count(*) filter(where t.codigo='V') vacaciones,count(*) filter(where t.codigo='R') retiros,count(*) filter(where t.codigo='.--') no_programados,sum(tm.horas) filter(where tm.es_cobertura) horas_cobertura
from public.tareo_marcaciones tm join public.tareo_periodos tp on tp.id=tm.periodo_id join public.vinculos_laborales vl on vl.id=tm.vinculo_laboral_id join public.tipos_marcacion t on t.id=tm.tipo_marcacion_id
group by tm.periodo_id,tp.anio,tp.mes,tm.vinculo_laboral_id,vl.persona_id,tm.sede_trabajada_id,tm.cliente_id;

